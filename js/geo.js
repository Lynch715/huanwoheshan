  function toCube(i) { return [CX[i], -CX[i] - CZ[i], CZ[i]]; }
  function dist(a, b) {
    const dx = CX[a] - CX[b], dz = CZ[a] - CZ[b], dy = -dx - dz;
    return Math.max(dx < 0 ? -dx : dx, dy < 0 ? -dy : dy, dz < 0 ? -dz : dz);
  }
  const ringCache = new Map();
  function ring(center, radius) {
    const key = center * 8 + radius;
    let r = ringCache.get(key);
    if (!r) { r = ringRaw(center, radius); if (radius <= 5) ringCache.set(key, r); }
    return r;
  }
  function ringRaw(center, radius) {
    // 返回 radius 以内全部格子
    const out = [center];
    const seen = new Set(out);
    let frontier = [center];
    for (let k = 0; k < radius; k++) {
      const nf = [];
      for (const f of frontier) for (const n of NBR[f]) if (!seen.has(n)) { seen.add(n); nf.push(n); out.push(n); }
      frontier = nf;
    }
    return out;
  }

