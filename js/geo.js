      if (inAny(lon, lat, R.hill)) t = (n2 > 0.85 ? T.FOREST : T.HILL);
      if (inAny(lon, lat, R.steppe)) t = T.STEPPE;
      if (inAny(lon, lat, R.desert)) t = T.DESERT;
